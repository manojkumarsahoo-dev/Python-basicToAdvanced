# Arithmetic Operators in Python
a=34
b=5
c=a+b
print(c)

#Assignment Operators
a=10
b=6
a+=5 # this is equivalent to a = a + 5
b-=3 # this is equivalent to b = b - 3
print(a)
print(b)

#comparison operators
d=5<4
e=5!=4
f=5==5
print(d)
print(e)
print(f)

#logical operators
g=(5>3) and (4<6) # this will return True because both conditions are true
h=(5>3) or (4>6) # this will return True because at least one condition is true
i=not(5>3) # this will return False because 5 is greater than 3
print(g)
print(h)
print(i)
